#!/usr/bin/env node
import { generateMcpTools } from "./index.js";

const USAGE =
  "Usage: cuple-mcp tools <routes-file> <variable> [--tsconfig <path>] > src/mcp-tools.ts";

const args = process.argv.slice(2);
const tsconfigAt = args.indexOf("--tsconfig");
const tsconfigPath = tsconfigAt >= 0 ? args.splice(tsconfigAt, 2)[1] : undefined;
const [command, filePath, variableName] = args;

if (command !== "tools" || !filePath || !variableName) {
  console.error(USAGE);
  process.exit(1);
}

const tools = generateMcpTools(filePath, variableName, { tsconfigPath });
process.stdout.write(
  `// Generated by \`cuple-mcp tools ${filePath} ${variableName}\`; rerun it when the routes change.
import type { McpTool } from "@cuple/mcp";

export const tools: McpTool[] = ${JSON.stringify(tools, null, 2)};
`,
);
